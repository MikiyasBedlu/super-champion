export type Lang = 'en' | 'am';
export const LANGS: Lang[] = ['en', 'am'];
export const isLang = (v: string | undefined): v is Lang => v === 'en' || v === 'am';

type Key = keyof (typeof DICT)['en'];
export type Vars = Record<string, string | number>;

export function translator(lang: Lang) {
  const table = DICT[lang] as Record<string, string>;
  const fallback = DICT.en as Record<string, string>;
  return (key: Key | string, vars?: Vars): string => {
    let s = table[key] ?? fallback[key] ?? String(key);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
export type T = ReturnType<typeof translator>;
